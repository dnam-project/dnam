class ResumeJobRequest(StrictModel):
    """Self-contained, wire-serializable job request for Two-Tier `.dnam-ckpt` iterative resume."""

    model_config = ConfigDict(
        extra="forbid",
        frozen=True,
        strict=True,
        arbitrary_types_allowed=True,
    )

    checkpoint_bytes: bytes
    new_stem_descriptors: list[WireStemDescriptor] = Field(default_factory=list)
    new_stems: list[TrainingStem] = Field(default_factory=list, exclude=True)
    config: TrainingConfig = Field(default_factory=TrainingConfig)
    force_tier2: bool = False

    @field_validator("checkpoint_bytes", mode="before")
    @classmethod
    def _decode_b64_checkpoint_bytes(cls, v: Any) -> bytes:
        if isinstance(v, str):
            return base64.b64decode(v.encode("ascii"))
        if isinstance(v, (bytes, bytearray, memoryview)):
            return bytes(v)
        raise TypeError("checkpoint_bytes must be bytes or base64 string")

    @field_serializer("checkpoint_bytes", when_used="json")
    def _encode_b64_checkpoint_bytes(self, v: bytes) -> str:
        return base64.b64encode(v).decode("ascii")


