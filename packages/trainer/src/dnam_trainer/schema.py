class TrainingStem(StrictModel):
    """Validated in-memory training stem holding dry excitation, wet target, and SHA-256
    provenance."""

    model_config = ConfigDict(
        extra="forbid",
        frozen=True,
        strict=True,
        arbitrary_types_allowed=True,
    )

    stem_id: str = Field(min_length=1)
    controls_meta: ControlCoords = Field(default_factory=dict)
    input_audio: NDArray[np.float32]
    target_audio: NDArray[np.float32]
    sample_rate_hz: int = Field(default=48_000, ge=44_100, le=96_000)
    noise_floor_dbfs: float = Field(default=-96.0, le=0.0)
    input_pcm_sha256: str = Field(default="", max_length=64)
    target_pcm_sha256: str = Field(default="", max_length=64)

    @model_validator(mode="before")
    @classmethod
    def _validate_and_hash_audio(cls, data: Any) -> Any:
        if not isinstance(data, Mapping):
            return data
        d = dict(data)
        if "input_audio" in d and "target_audio" in d:
            in_arr = coerce_audio_f32(d["input_audio"], allow_stereo=False)
            tgt_arr = coerce_audio_f32(d["target_audio"], allow_stereo=True)
            in_len = int(in_arr.shape[-1])
            tgt_len = int(tgt_arr.shape[-1])
            if in_len != tgt_len:
                raise ValueError(
                    f"Stem '{d.get('stem_id', '?')}' input length ({in_len}) "
                    f"does not match target length ({tgt_len})"
                )
            d["input_audio"] = in_arr
            d["target_audio"] = tgt_arr
            if not d.get("input_pcm_sha256"):
                d["input_pcm_sha256"] = compute_pcm_sha256(in_arr)
            if not d.get("target_pcm_sha256"):
                d["target_pcm_sha256"] = compute_pcm_sha256(tgt_arr)
        return d

    @property
    def num_samples(self) -> int:
        """Number of audio frames `L` in this stem."""
        return int(self.input_audio.shape[-1])

    @property
    def is_stereo_target(self) -> bool:
        """Returns `True` if `target_audio` has stereo shape `(2, L)`."""
        return self.target_audio.ndim == 2 and self.target_audio.shape[0] == 2

    def target_stereo_2d(self) -> NDArray[np.float32]:
        """Returns `target_audio` expanded to `(2, L)` stereo."""
        if self.target_audio.ndim == 2:
            return self.target_audio
        return np.stack([self.target_audio, self.target_audio], axis=0)

    def to_wire_descriptor(
        self,
        *,
        input_ref: StemAudioRef | None = None,
        target_ref: StemAudioRef | None = None,
    ) -> WireStemDescriptor:
        """Builds a JSON-serializable `WireStemDescriptor` for `TrainingJobRequest`."""
        in_ref = input_ref or InMemoryPcmRef(
            pcm_sha256=self.input_pcm_sha256,
            sample_rate_hz=self.sample_rate_hz,
            channels=1,
            num_samples=self.num_samples,
        )
        tgt_channels = 2 if self.is_stereo_target else 1
        tgt_ref = target_ref or InMemoryPcmRef(
            pcm_sha256=self.target_pcm_sha256,
            sample_rate_hz=self.sample_rate_hz,
            channels=tgt_channels,
            num_samples=self.num_samples,
        )
        return WireStemDescriptor(
            stem_id=self.stem_id,
            controls_meta=dict(self.controls_meta),
            input_ref=in_ref,
            target_ref=tgt_ref,
            noise_floor_dbfs=self.noise_floor_dbfs,
        )


